def classify(code, output):
    failure_match = re.search(r"failures=(\d+)", output)
    error_match = re.search(r"errors=(\d+)", output)
    failures = int(failure_match.group(1)) if failure_match else 0
    errors = int(error_match.group(1)) if error_match else 0
    if failures > 0 or errors > 0:
        return "caught"
    if code == 0 and re.search(r"(?m)^OK$", output):
        return "survived"
    return "crashed"


def sandbox_env(sandbox):
    env = os.environ.copy()
    for key in list(env):
        if key.startswith("GIT_") or key in ("PYTHONPATH", "PYTHONHOME"):
            del env[key]
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["HOME"] = sandbox
    return env


def prepare(source_text, module):
    sandbox = tempfile.mkdtemp(prefix="org-mutate-")
    with open(os.path.join(sandbox, "render.py"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(source_text)
    tests_dir = os.path.join(sandbox, "tests")
    os.makedirs(tests_dir)
    filename = module.split(".")[-1] + ".py"
    shutil.copyfile(
        os.path.join(PROJECT, "tests", filename),
        os.path.join(tests_dir, filename),
    )
    return sandbox


def run_suite(sandbox, module):
    proc = subprocess.Popen(
        [sys.executable, "-B", "-m", "unittest", module],
        cwd=sandbox,
        env=sandbox_env(sandbox),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        start_new_session=True,
    )
    try:
        stdout, stderr = proc.communicate(timeout=120)
    except subprocess.TimeoutExpired as expired:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except OSError:
            pass
        stdout, stderr = proc.communicate()
        output = (expired.stdout or "") + (stdout or "") + "\n" + (expired.stderr or "") + (stderr or "")
        return "timed out", output
    output = (stdout or "") + "\n" + (stderr or "")
    return classify(proc.returncode, output), output


def run_one(source_text, old, new, module):
    mutated = source_text.replace(old, new, 1)
    try:
        compile(mutated, "render.py", "exec")
    except SyntaxError:
        return "does not compile", ""
    sandbox = prepare(mutated, module)
    try:
        return run_suite(sandbox, module)
    finally:
        shutil.rmtree(sandbox, ignore_errors=True)


def baseline(source_text):
    seen = []
    for _name, _old, _new, module in MUTATIONS:
        if module not in seen:
            seen.append(module)
    for module in seen:
        sandbox = prepare(source_text, module)
        try:
            status, _output = run_suite(sandbox, module)
        finally:
            shutil.rmtree(sandbox, ignore_errors=True)
        if status != "survived":
            sys.stderr.write("baseline failed: %s\n" % module)
            return False
    return True


def main():
    with open(SOURCE, encoding="utf-8") as handle:
        source_text = handle.read()
    for name, old, new, _module in MUTATIONS:
        count = source_text.count(old)
        if count != 1 or old == new:
            sys.stderr.write("mutation %s matches %d times\n" % (name, count))
            return 2
    if not baseline(source_text):
        return 2
    caught = 0
    total = len(MUTATIONS)
    log_dir = None
    for name, old, new, module in MUTATIONS:
        status, output = run_one(source_text, old, new, module)
        print("%s %s" % (name, status))
        if status == "caught":
            caught += 1
        else:
            if log_dir is None:
                log_dir = tempfile.mkdtemp(prefix="org-mutate-logs-")
            with open(os.path.join(log_dir, "%s.log" % name), "w", encoding="utf-8") as handle:
                handle.write(output)
    if log_dir is not None:
        print("logs: %s" % log_dir)
    print("caught %d of %d" % (caught, total))
    return 0 if caught == total else 1


if __name__ == "__main__":
    sys.exit(main())
