#!/usr/bin/env python3
"""Generate org views from org.json and fail when a view was edited by hand."""

import json
import os
import stat
import sys
import tempfile

HEADER = "<!-- Generated from org.json by render.py. Do not edit this file: change org.json, then run python3 render.py -->"
NOTICE = "<!-- Generated from org.json. Edits between these two markers are overwritten. -->"
TOP_FIELDS = {"org", "people", "teams", "outputs", "allow_shared_heads"}
TEAM_FIELDS = {"name", "head", "measured_by", "members", "owns"}
OUTPUT_FIELDS = {"view", "file", "block"}
BLOCK_CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-"
def cell(value):
    return str(value).replace("|", "\\|")
def view_roster(org):
    teams = org["teams"]
    show_members = any(team.get("members") for team in teams)
    show_owns = any(team.get("owns") for team in teams)
    headers = ["Team", "Head"] + (["Members"] if show_members else []) + ["Measured by"]
    if show_owns:
        headers.append("Owns")
    rows = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _col in headers) + " |"]
    teams_in_file_order = list(teams)
    for team in teams_in_file_order:
        values = [cell(team["name"]), cell(team["head"])]
        if show_members:
            values.append(cell(", ".join(team.get("members") or [])))
        values.append(cell(team["measured_by"]))
        if show_owns:
            values.append(cell(", ".join(team.get("owns") or [])))
        rows.append("| " + " | ".join(values) + " |")
    return "\n".join(rows) + "\n"
def view_owners(org):
    owned = []
    for team in org["teams"]:
        for thing in team.get("owns") or []:
            owned.append((thing.casefold(), thing, team["name"], team["head"]))
    owned.sort(key=lambda row: (row[0], row[1]))
    if not owned:
        return ""
    return "\n".join("- %s: %s (%s)" % (thing, team, head) for _, thing, team, head in owned) + "\n"
VIEWS = {"roster": view_roster, "owners": view_owners}
TITLES = {"roster": "# Roster: %s", "owners": "# Who owns what: %s"}
def whole_text(org, view_name, body):
    org_name = org.get("org") if isinstance(org.get("org"), str) else ""
    title = TITLES[view_name] % org_name + "\n\n" if view_name in TITLES else ""
    text = HEADER + "\n\n" + title + body
    return text if text.endswith("\n") else text + "\n"
def block_text(body):
    text = NOTICE + "\n" + body
    return text if text.endswith("\n") else text + "\n"
def path_parts(path):
    if not isinstance(path, str) or path == "" or os.path.isabs(path) or ".." in path.split("/"):
        return None
    parts = [part for part in path.split("/") if part not in ("", ".")]
    return parts or None
def line_break(value, place, broken):
    if isinstance(value, str) and ("\n" in value or "\r" in value):
        broken.append("%s holds a line break" % place)
def text_of(value):
    return value if isinstance(value, str) else ""
def unknown(mapping, allowed, place, broken):
    for key in mapping:
        if key not in allowed:
            broken.append("%s has an unknown field %s" % (place, key))
def check_rules(org):
    broken = []
    unknown(org, TOP_FIELDS, "org.json", broken)
    if "org" in org and not isinstance(org.get("org"), str): broken.append("org is not text")
    else: line_break(org.get("org", ""), "org", broken)
    allow = org.get("allow_shared_heads", False)
    if "allow_shared_heads" in org and not isinstance(allow, bool):
        broken.append("allow_shared_heads is not true or false")
        allow = False
    people = org.get("people", [])
    if not isinstance(people, list):
        broken.append("people is not a list")
        people = []
    seen_people, people_set = set(), set()
    for person in people:
        if not isinstance(person, str):
            broken.append("a person is not text")
            continue
        line_break(person, "person %s" % person, broken)
        if person in seen_people: broken.append("%s is listed more than once in people" % person)
        seen_people.add(person)
        if person: people_set.add(person)
    teams = org.get("teams", [])
    if not isinstance(teams, list):
        broken.append("teams is not a list")
        teams = []
    elif len(teams) == 0:
        broken.append("there is no team")
    seen_teams, head_of, covered, owned_by = set(), {}, set(), {}
    for index, team in enumerate(teams):
        if not isinstance(team, dict):
            broken.append("a team is not an object")
            continue
        name = text_of(team.get("name"))
        label = "team %s" % name if name else "team %d" % (index + 1)
        unknown(team, TEAM_FIELDS, label, broken)
        if name == "": broken.append("a team has an empty name")
        else:
            line_break(name, "%s name" % label, broken)
            if name in seen_teams: broken.append("the team name %s is used more than once" % name)
            seen_teams.add(name)
        head = text_of(team.get("head"))
        if head == "": broken.append("%s has an empty head" % label)
        else:
            line_break(head, "%s head" % label, broken)
            if head not in people_set: broken.append("%s has head %s, who is not in people" % (label, head))
            head_of.setdefault(head, []).append(name)
            covered.add(head)
        measure = text_of(team.get("measured_by"))
        if measure == "": broken.append("%s has an empty measured_by" % label)
        else: line_break(measure, "%s measured_by" % label, broken)
        members = team.get("members", [])
        if "members" in team and not isinstance(members, list):
            broken.append("%s field members is not a list" % label)
            members = []
        for member in members or []:
            if not isinstance(member, str) or member == "":
                broken.append("%s has an empty member" % label)
                continue
            line_break(member, "%s member %s" % (label, member), broken)
            if member not in people_set: broken.append("%s has member %s, who is not in people" % (label, member))
            covered.add(member)
        things = team.get("owns", [])
        if "owns" in team and not isinstance(things, list):
            broken.append("%s field owns is not a list" % label)
            things = []
        for thing in things or []:
            if not isinstance(thing, str) or thing == "":
                broken.append("%s has an empty owned thing" % label)
                continue
            line_break(thing, "owned thing %s" % thing, broken)
            key = thing.casefold()
            if key in owned_by: broken.append("%s is owned by both %s and %s" % (thing, owned_by[key], name or label))
            else: owned_by[key] = name or label
    if allow is not True:
        for person, names in head_of.items():
            names = [item for item in names if item]
            if len(names) == 2: broken.append("%s heads both %s and %s" % (person, names[0], names[1]))
            elif len(names) > 2: broken.append("%s heads %s" % (person, ", ".join(names)))
    for person in people:
        if isinstance(person, str) and person and person not in covered:
            broken.append("%s heads no team and is a member of none" % person)
    outputs = org.get("outputs", [])
    if not isinstance(outputs, list):
        broken.append("outputs is not a list")
        outputs = []
    seen, whole, blocks = set(), set(), set()
    for index, output in enumerate(outputs):
        if not isinstance(output, dict):
            broken.append("an output is not an object")
            continue
        rel, view = output.get("file"), output.get("view")
        shown = rel if isinstance(rel, str) and rel else "output %d" % (index + 1)
        unknown(output, OUTPUT_FIELDS, "output %s" % shown, broken)
        line_break(text_of(rel), "output %s file" % shown, broken)
        line_break(text_of(view), "output %s view" % shown, broken)
        parts = path_parts(rel) if isinstance(rel, str) and rel else None
        if not isinstance(rel, str) or rel == "": broken.append("an output has an empty file")
        elif parts is None: broken.append("output %s is outside the root" % rel)
        if parts is not None and len(parts) == 1:
            folded = parts[0].casefold()
            if folded == "org.json" or folded == "render.py":
                broken.append("output %s would overwrite %s" % (rel, folded))
        if not isinstance(view, str) or view not in VIEWS: broken.append("output %s names an unknown view %s" % (shown, view))
        block = output["block"] if "block" in output else None
        if "block" in output:
            line_break(text_of(block), "output %s block" % shown, broken)
            valid = isinstance(block, str) and block and all(char in BLOCK_CHARS for char in block)
            if not valid: broken.append("output %s has an invalid block name" % shown)
        if not parts: continue
        label = "/".join(parts)
        ident = (label, block if isinstance(block, str) else None)
        if ident in seen:
            if block: broken.append("output %s block %s is listed twice" % (label, block))
            else: broken.append("output %s is listed twice" % label)
        seen.add(ident)
        (blocks if isinstance(block, str) else whole).add(label)
    for label in whole:
        if label in blocks: broken.append("output %s is written whole and also as a block" % label)
    return broken
def locate(content, name):
    begin, end = "<!-- org:%s:begin -->" % name, "<!-- org:%s:end -->" % name
    offset, begin_inner = 0, None
    for line in content.split("\n"):
        line_start, next_offset = offset, offset + len(line)
        has_nl = next_offset < len(content) and content[next_offset] == "\n"
        if line == begin and begin_inner is None and has_nl:
            begin_inner = next_offset + 1
        elif line == end and begin_inner is not None:
            return begin_inner, line_start
        if not has_nl:
            return None
        offset = next_offset + 1
    return None
def read_text(path):
    with open(path, "rb") as handle:
        return handle.read().decode("utf-8")
def same_text(left, right):
    return left == right
def first_diff(disk, expected):
    disk_lines, expected_lines = disk.split("\n"), expected.split("\n")
    for index in range(max(len(disk_lines), len(expected_lines))):
        disk_line = disk_lines[index] if index < len(disk_lines) else None
        expected_line = expected_lines[index] if index < len(expected_lines) else None
        if disk_line != expected_line:
            return index + 1, (disk_line or "")[:100], (expected_line or "")[:100]
    return 1, "", ""
def file_text(path):
    if not os.path.isfile(path):
        return None
    try:
        return read_text(path)
    except (OSError, UnicodeDecodeError):
        return None
def build(org, root, mode):
    items, states = [], {}
    for spec in org.get("outputs", []):
        rel = spec["file"]
        block = spec["block"] if "block" in spec else None
        path = os.path.join(root, *path_parts(rel))
        if os.path.isdir(path):
            return "%s is a folder" % rel, items
        body = VIEWS[spec["view"]](org)
        if block:
            new = block_text(body)
            reason = "%s has no org:%s block" % (rel, block)
            state = states.get(rel)
            if state is None:
                text = file_text(path)
                state = states[rel] = {"path": path, "original": text, "current": text, "rel": rel} if text is not None else {}
            found = locate(state["current"], block) if state.get("current") is not None else None
            if found is None:
                if mode != "check":
                    return reason, items
                items.append({"rel": rel, "block": block, "drift": "DRIFT: " + reason})
                continue
            start, end = found
            old = state["current"][start:end]
            origin = state.get("original")
            anchor = locate(origin, block) if origin is not None else None
            if anchor is None:
                line_base = state["current"][:start].count("\n")
            else:
                line_base = origin[:anchor[0]].count("\n")
            state["current"] = state["current"][:start] + new + state["current"][end:]
            items.append({"rel": rel, "block": block, "old": old, "new": new, "state": state, "line_base": line_base})
            continue
        new = whole_text(org, spec["view"], body)
        if mode == "check" and not os.path.isfile(path):
            items.append({"rel": rel, "block": None, "drift": "DRIFT: %s is missing" % rel})
            continue
        original = file_text(path)
        state = {"path": path, "original": original, "current": new, "rel": rel}
        items.append({"rel": rel, "block": None, "old": original, "new": new, "state": state})
    return None, items
class _WriteFailed(Exception):
    def __init__(self, rel, error):
        Exception.__init__(self, str(rel))
        self.rel = rel
        self.error = error
def commit(items):
    # COMMIT_WRITES
    seen, staged, temps = set(), [], []
    for item in items:
        state = item.get("state")
        if state is None or state["path"] in seen or state.get("current") is None:
            continue
        seen.add(state["path"])
        if state.get("original") is not None and same_text(state["original"], state["current"]):
            continue
        staged.append(state)
    fresh = None
    try:
        for state in staged:
            folder = os.path.dirname(state["path"]) or "."
            try:
                os.makedirs(folder, exist_ok=True)
                fd, tmp = tempfile.mkstemp(prefix=".render-", dir=folder)
                temps.append((tmp, state))
                with os.fdopen(fd, "wb") as handle:
                    handle.write(state["current"].encode("utf-8"))
            except OSError as error:
                raise _WriteFailed(state["rel"], error)
        for tmp, state in temps:
            dest = state["path"]
            try:
                if os.path.exists(dest):
                    mode = stat.S_IMODE(os.stat(dest).st_mode)
                else:
                    if fresh is None:
                        old_mask = os.umask(0)
                        os.umask(old_mask)
                        fresh = 0o666 & ~old_mask
                    mode = fresh
                os.chmod(tmp, mode)
                os.replace(tmp, dest)
            except OSError as error:
                raise _WriteFailed(state["rel"], error)
    finally:
        for tmp, _state in temps:
            if os.path.exists(tmp):
                os.remove(tmp)
def emit_write(items):
    changed = 0
    for item in items:
        old, new = item.get("old"), item.get("new")
        wrote = old is None or not same_text(old, new)
        suffix = " (block %s)" % item["block"] if item.get("block") else ""
        print("%s %s%s" % ("wrote" if wrote else "unchanged", item["rel"], suffix))
        changed += wrote
    print("rendered %d outputs from org.json (%d changed)" % (len(items), changed))
def emit_check(items):
    drift = 0
    for item in items:
        if item.get("drift"):
            print(item["drift"])
            drift += 1
            continue
        old, new = item.get("old"), item.get("new")
        if old is not None and same_text(old, new):
            continue
        number, disk_line, expected_line = first_diff("" if old is None else old, new)
        number += item.get("line_base", 0)
        print("DRIFT: %s line %d differs" % (item["rel"], number))
        print("  on disk:  %s" % disk_line)
        print("  expected: %s" % expected_line)
        drift += 1
    if drift:
        print("%d of %d outputs out of date. Change org.json, then run: python3 render.py" % (drift, len(items)))
        return 1  # drift exit
    print("views match org.json (%d outputs)" % len(items))
    return 0  # match exit
def fail_load(mode, reason):
    print("could not %s: %s" % ("check" if mode == "check" else "render", reason))
    return 2  # missing source exit
def load_org(root):
    try:
        raw = read_text(os.path.join(root, "org.json"))
    except FileNotFoundError:
        return "org.json is missing"
    except (OSError, UnicodeDecodeError):
        return "org.json is not readable"
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        return "org.json is not valid JSON"
    return data if isinstance(data, dict) else "org.json is not a JSON object"
def parse_args(argv):
    mode, view_name, root, index = "write", None, None, 0
    while index < len(argv):
        arg, nxt = argv[index], argv[index + 1] if index + 1 < len(argv) else ""
        if arg == "--check" and mode != "view":
            mode = "check"
        elif arg == "--view" and mode != "check" and nxt and not nxt.startswith("-"):
            mode, view_name, index = "view", nxt, index + 1
        elif arg == "--root" and root is None and nxt and not nxt.startswith("-"):
            root, index = nxt, index + 1
        else:
            return None
        index += 1
    return mode, view_name, root
def resolve_root(root_arg):
    if root_arg:
        return root_arg
    return os.path.dirname(os.path.abspath(__file__))
def report_rules(broken, mode):
    for sentence in broken:
        print("RULE: " + sentence)
    tail = "nothing was checked" if mode == "check" else "nothing was written"
    print("%d rules broken in org.json; %s" % (len(broken), tail))
    return 1  # rules exit
def main(argv):
    parsed = parse_args(argv)
    if parsed is None:
        sys.stderr.write("usage: python3 render.py [--check] [--view NAME] [--root DIR]\n")
        return 2
    mode, view_name, root_arg = parsed
    root = resolve_root(root_arg)
    loaded = load_org(root)
    if isinstance(loaded, str): return fail_load(mode, loaded)
    if mode == "view" and view_name not in VIEWS:
        sys.stderr.write("usage: unknown view %s\n" % view_name)
        return 2
    broken = check_rules(loaded)
    if broken: return report_rules(broken, mode)
    if mode == "view":
        sys.stdout.write(VIEWS[view_name](loaded))
        return 0
    reason, items = build(loaded, root, mode)
    if reason: return fail_load(mode, reason)
    if mode == "check": return emit_check(items)
    try:
        commit(items)
    except _WriteFailed as failed:
        return fail_load(mode, "%s could not be written (%s)" % (failed.rel, failed.error))
    emit_write(items)
    return 0
if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
